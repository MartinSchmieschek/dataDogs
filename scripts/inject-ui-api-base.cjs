'use strict';

/**
 * Writes ui-app/src/app/config/api-base.inject.ts from PUBLIC_API_BASE_URL (.env).
 * No assertRequiredDbEnv — may run without a DB (UI-only build).
 */
const fs = require('fs');
const path = require('path');
const dotenv = require('dotenv');

const root = path.join(__dirname, '..');
const nodeEnv = process.env.NODE_ENV || 'development';
const files = ['.env', '.env.local', `.env.${nodeEnv}`, `.env.${nodeEnv}.local`];
for (const f of files) {
    const p = path.join(root, f);
    if (fs.existsSync(p)) dotenv.config({ path: p, override: true });
}

/**
 * `.env` often sets PUBLIC_API_BASE_URL=localhost; if the key is missing in `.env.integration` /
 * `.env.production`, the value would stick. For those profiles: when at least one profile file
 * exists, PUBLIC_API_BASE_URL is taken only from those files (order, last wins) — if the key
 * is missing everywhere, we do not inherit from `.env` (→ same-origin default).
 */
function applyProfilePublicApiBase() {
    const profiles =
        nodeEnv === 'integration'
            ? ['.env.integration', '.env.integration.local']
            : nodeEnv === 'production'
              ? ['.env.production', '.env.production.local']
              : [];
    if (!profiles.length) return;

    let lastDefined;
    let anyProfileFile = false;
    for (const f of profiles) {
        const p = path.join(root, f);
        if (!fs.existsSync(p)) continue;
        anyProfileFile = true;
        const parsed = dotenv.parse(fs.readFileSync(p, 'utf8'));
        if (Object.prototype.hasOwnProperty.call(parsed, 'PUBLIC_API_BASE_URL')) {
            lastDefined = parsed.PUBLIC_API_BASE_URL;
        }
    }
    if (!anyProfileFile) return;
    if (lastDefined !== undefined) {
        process.env.PUBLIC_API_BASE_URL = lastDefined;
    } else {
        delete process.env.PUBLIC_API_BASE_URL;
    }
}
applyProfilePublicApiBase();

// development: default localhost (ng serve / local backend).
// integration | production: if unset → empty = same origin (window.location.origin in the browser)
// so staging/deploy (e.g. Render) does not bake localhost:3000 into the bundle.
const explicit = process.env.PUBLIC_API_BASE_URL;
let base;
if (explicit !== undefined) {
    base = String(explicit).trim();
} else if (nodeEnv === 'integration' || nodeEnv === 'production') {
    base = '';
} else {
    base = 'http://localhost:3000';
}
base = base.replace(/\/+$/, '');

// Common Render mistake: PUBLIC_API_BASE_URL=http://localhost:3000 copied from an example —
// do not bake that in for staging/prod; the browser should use window.location.origin.
if ((nodeEnv === 'integration' || nodeEnv === 'production') && base) {
    try {
        const u = new URL(base.startsWith('http://') || base.startsWith('https://') ? base : `https://${base}`);
        if (u.hostname === 'localhost' || u.hostname === '127.0.0.1') {
            base = '';
        }
    } catch {
        /* keep base */
    }
}

const preferDeliveryOrigin = nodeEnv === 'integration' || nodeEnv === 'production';

const outPath = path.join(root, 'ui-app', 'src', 'app', 'config', 'api-base.inject.ts');
const body = `/**
 * Auto-generated by scripts/inject-ui-api-base.cjs — do not edit by hand.
 * Source: PUBLIC_API_BASE_URL in repo root .env (see .env.example).
 * Empty string means same origin in the browser (SPA and API on the same origin).
 *
 * API_PREFER_DELIVERY_ORIGIN: set for integration/production builds so absolute links
 * on staging/prod do not fall back to localhost unless intended.
 */
export const API_PREFER_DELIVERY_ORIGIN = ${preferDeliveryOrigin};
export const API_ORIGIN_INJECTED = ${JSON.stringify(base)};
`;
fs.writeFileSync(outPath, body, 'utf8');
console.log('[inject-ui-api-base] PUBLIC_API_BASE_URL ->', base === '' ? '(empty → same origin in browser)' : base);
console.log('[inject-ui-api-base] API_PREFER_DELIVERY_ORIGIN ->', preferDeliveryOrigin);
