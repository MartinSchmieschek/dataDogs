'use strict';

/**
 * Schreibt ui-app/src/app/config/api-base.inject.ts aus PUBLIC_API_BASE_URL (.env).
 * Kein assertRequiredDbEnv — darf auch ohne DB laufen (reiner UI-Build).
 */
const fs = require('fs');
const path = require('path');
const dotenv = require('dotenv');

const root = path.join(__dirname, '..');
const nodeEnv = process.env.NODE_ENV || 'development';
const files = ['.env', '.env.local', `.env.${nodeEnv}`, `.env.${nodeEnv}.local`];
for (const f of files) {
    const p = path.join(root, f);
    if (fs.existsSync(p)) dotenv.config({ path: p, override: true });
}

let base = (process.env.PUBLIC_API_BASE_URL || 'http://localhost:3000').trim();
base = base.replace(/\/+$/, '');

const outPath = path.join(root, 'ui-app', 'src', 'app', 'config', 'api-base.inject.ts');
const body = `/**
 * Auto-generated by scripts/inject-ui-api-base.cjs — nicht manuell bearbeiten.
 * Quelle: PUBLIC_API_BASE_URL in Repo-Root-.env (siehe .env.example).
 * Leer lassen für Same-Origin im Browser (SPA und API unter derselben Origin).
 */
export const API_ORIGIN_INJECTED = ${JSON.stringify(base)};
`;
fs.writeFileSync(outPath, body, 'utf8');
console.log('[inject-ui-api-base] PUBLIC_API_BASE_URL ->', base === '' ? '(leer → Same-Origin im Browser)' : base);
